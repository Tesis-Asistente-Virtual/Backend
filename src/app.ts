import express from 'express';
import { errorHandler } from './shared/infrastructure/http/error-handler.js';
import { authenticationRouter } from './modules/authentication/interfaces/rest/sign-up-routes.js';
import { signInRouter } from './modules/authentication/interfaces/rest/sign-in-routes.js';
import { sessionRouter } from './modules/authentication/interfaces/rest/session-routes.js';
import { usersRouter } from './modules/users/interfaces/rest/users-routes.js';
import { conversationsRouter } from './modules/conversations/interfaces/rest/conversations-routes.js';
import { openApiRouter } from './shared/infrastructure/http/openapi-routes.js';
import { consentRouter } from './modules/consent/interfaces/rest/consent-routes.js';
import { preliminaryAssessmentsRouter } from './modules/preliminary-assessment/interfaces/rest/preliminary-assessment-routes.js';
import { monitoringRouter } from './modules/longitudinal-monitoring/interfaces/rest/monitoring-routes.js';
import { conversationSignalExtractionRouter } from './modules/conversational-processing/interfaces/rest/conversation-signal-extraction-routes.js';
import { conversationalSignalAnalysisRouter } from './modules/conversational-processing/interfaces/rest/conversational-signal-analysis-routes.js';
import { env } from './config/env.js';
import { createCorsMiddleware } from './shared/infrastructure/http/cors-middleware.js';
import { recommendationsRouter } from './modules/recommendations/interfaces/rest/recommendations-routes.js';
import { psychologicalReferralRouter } from './modules/psychological-referrals/interfaces/rest/psychological-referral-routes.js';
export const app = express();
app.use(createCorsMiddleware(env.corsAllowedOrigins));
app.use(express.json());
app.use(openApiRouter);
app.get('/health', (_req, res) => res.json({ status: 'ok' }));
app.use('/api/v1/auth', authenticationRouter);
app.use('/api/v1/auth', signInRouter);
app.use('/api/v1/auth', sessionRouter);
app.use('/api/v1/users', usersRouter);
app.use('/api/v1/conversations', conversationsRouter);
app.use('/api/v1/conversations', conversationSignalExtractionRouter);
app.use('/api/v1', conversationalSignalAnalysisRouter);
app.use('/api/v1/consents', consentRouter);
app.use('/api/v1/preliminary-assessments', preliminaryAssessmentsRouter);
app.use('/api/v1/monitoring', monitoringRouter);
app.use('/api/v1/me/recommendations', recommendationsRouter);
app.use('/api/v1/me/psychological-referrals', psychologicalReferralRouter);
app.use(errorHandler);
